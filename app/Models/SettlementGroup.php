    // protected $fillable = [];
    // protected $hidden = [];

    /*
    |--------------------------------------------------------------------------
    | FUNCTIONS
    |--------------------------------------------------------------------------
    */

    /*
    |--------------------------------------------------------------------------
    | RELATIONS
    |--------------------------------------------------------------------------
    */

    public function settlement(): BelongsTo
    {
        return $this->belongsTo(Settlement::class);
    }

    public function settlements(): BelongsToMany
    {
        return $this->belongsToMany(Settlement::class);
    }
